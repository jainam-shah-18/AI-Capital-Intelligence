-- Run in a Snowflake worksheet with a role permitted to create these objects.
-- This warehouse is intentionally X-Small and auto-suspends quickly to control credits.
CREATE WAREHOUSE IF NOT EXISTS ACI_XS_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS AI_CAPITAL_INTELLIGENCE;
CREATE SCHEMA IF NOT EXISTS AI_CAPITAL_INTELLIGENCE.RAW;

CREATE TABLE IF NOT EXISTS AI_CAPITAL_INTELLIGENCE.RAW.FINANCIAL_METRICS (
  TICKER VARCHAR(10),
  COMPANY_NAME VARCHAR(200),
  METRIC VARCHAR(100),
  XBRL_TAG VARCHAR(200),
  PERIOD_TYPE VARCHAR(20),
  PERIOD_START DATE,
  PERIOD_END DATE,
  FISCAL_YEAR NUMBER(4,0),
  FISCAL_PERIOD VARCHAR(10),
  FORM VARCHAR(10),
  FILED_DATE DATE,
  ACCESSION_NUMBER VARCHAR(30),
  CURRENCY VARCHAR(3),
  VALUE_USD FLOAT,
  SOURCE VARCHAR(100)
);

-- Verify the warehouse remains suspended after setup:
SHOW WAREHOUSES LIKE 'ACI_XS_WH';
